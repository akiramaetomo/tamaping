function sourcePreset(
  name: string,
  nextName: string,
  nextFormationLabel?: string | null,
  initialFormation?: FactoryPresetInitialFormation,
): FactoryPresetData {
  const preset = SOURCE_PRESET_DEFINITION_DATA.find((candidate) => candidate.name === name);
  if (!preset) {
    throw new Error(`Missing factory preset source: ${name}`);
  }
  const { formationLabel: _formationLabel, ...presetWithoutFormationLabel } = preset;
  const basePreset = nextFormationLabel === null ? presetWithoutFormationLabel : preset;
  return {
    ...basePreset,
    name: nextName,
    ...(typeof nextFormationLabel === 'string' ? { formationLabel: nextFormationLabel } : {}),
    ...(initialFormation ? { initialFormation } : {}),
  };
}

